from aiogram import Router
from aiogram.filters import CommandStart
from aiogram.types import InputRichMessage, Message

router = Router()

START_MESSAGE = """# 🎓 Твой учебный помощник

Все важное для учёбы — в одном чате.

/profile — твоя группа и настройка напоминаний.

## ⏳ Дедлайны
Добавляй сроки сдачи работ, чтобы помнить, **что и когда нужно сдать**.

## 🗓 Расписание
Получай расписание занятий и планируй свой учебный день.

/day - расписание на день.
/week - расписание на неделю.
/semester - полное расписание текущего семестра по дням недели с периодами занятий.

Команда /reminder — расписание на сегодня с кнопкой дедлайнов на сегодня и завтра.
Команда /deadlines — только дедлайны на текущую неделю, с понедельника по воскресенье.
Команда /all_deadlines — все дедлайны начиная с сегодня включительно.
Время и статус уведомлений можно изменить кнопками в /profile.

/deadline — добавить ДЗ с подтверждением.
/delete_deadline — выбрать и удалить ДЗ своей группы.

## 🎯 Подготовка к сессии
/session - задания до сессии по предметам.
/session_add - добавить общее требование с необязательным сроком.

## 📚 Задания
Узнавай, что задали, и держи учебные задачи под рукой.

---

> Меньше времени на поиски — больше на учёбу и отдых.
"""


@router.message(CommandStart())
async def command_start(ms: Message):
    await ms.answer_rich(InputRichMessage(markdown=START_MESSAGE))
